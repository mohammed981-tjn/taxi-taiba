import 'dart:math';

/// رمز الجلسة الذي يجمع بحثاً واحداً في فاتورة واحدة.
///
/// إكمال العناوين يُحاسَب عند Google **لكل طلب**، والطلب يُرسَل مع كل حرف.
/// فراكبٌ يكتب «المدينة المنورة» يُرسل أربعة عشر طلباً ليختار عنواناً واحداً،
/// ويُحاسَب على أربعة عشر.
///
/// ورمز الجلسة يقول لـGoogle إنّ هذه الطلبات كلّها بحثٌ واحد انتهى باختيار
/// واحد: تُرسَل مع كل حرف ومع طلب التفاصيل الذي يليها، فتُحسب جلسةً واحدة لا
/// أربعة عشر. وشرطه أن **يُجدَّد بعد كل اختيار** — رمزٌ لا يُجدَّد يجعل بحث
/// اليوم كلّه جلسةً واحدة، فترفضه Google وتعود إلى المحاسبة بالطلب.
///
/// وهذا ليس تحسيناً مؤجَّلاً: الحدّ المجّاني عشرة آلاف طلب شهرياً. بالطلب
/// يكفي نحو سبعمئة بحث، وبالجلسة يكفي عشرة آلاف.
class PlacesSession {
  const PlacesSession._();

  static final Random _random = Random.secure();

  static String _token = _mint();

  /// يُرسَل مع كل استعلام إكمال ومع طلب التفاصيل الذي يختمه.
  static String get token => _token;

  /// يُستدعى بعد اختيار عنوان — أي بعد `place/details`.
  static void renew() => _token = _mint();

  static String _mint() {
    const String hex = '0123456789abcdef';
    final StringBuffer out = StringBuffer();
    for (int i = 0; i < 32; i++) {
      out.write(hex[_random.nextInt(16)]);
    }
    return out.toString();
  }
}

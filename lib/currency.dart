import 'package:flutter_projects/market.dart';

/// رمز العملة — من السوق الفعّال.
///
/// كان `₦` مكتوباً في خمسة مواضع: النايرا النيجيرية، عملة القالب الأصلي. وهو
/// الأخ الأوضح لـ`country:NG` — لا يفشل ولا يُنبَّه عليه، فقط يعرض على راكب
/// سعراً بعملة بلدٍ آخر.
///
/// وصار يأتي من `lib/market.dart` لا من متغيّر بناء مستقلّ: العملة والبلد
/// يتغيّران معاً دائماً، وفصلُهما يسمح بتركيبةٍ لا معنى لها — بحثٌ في السعودية
/// بأسعار بالجنيه السوداني.
///
/// وحين تُبنى شاشة التسعير سينتقل السعر إلى القاعدة؛ أمّا العملة فتبقى هنا
/// لأنها خاصيّة سوق لا رقمٌ يُضبط.
String get currencySymbol => market.currency;

/// مبلغ بعملته، بمسافة فاصلة.
String money(Object? amount) {
  final String text = '$amount'.trim();
  return text.isEmpty ? currencySymbol : '$currencySymbol $text';
}

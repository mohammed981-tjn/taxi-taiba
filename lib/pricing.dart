/// التسعير — في مكان واحد.
///
/// كان في ثلاثة، وكان كلٌّ منها يعطي رقماً مختلفاً لنفس الرحلة:
///
///   شاشة اختيار الفئة   `200 + km × factor × 100`   ← ٦٠٠ لرحلة ١٠ كم
///   بطاقة التأكيد تحتها  `fareBreakdown × 0.8`      ← ١٦٨
///   ما يُحصَّل فعلاً      `fareBreakdown.total`       ← ٢١٠
///
/// ثلاثة أسعار لرحلة واحدة، والمدفوع لا يطابق أيّاً منها — وزيادةٌ ٢٥٪ فوق آخر
/// رقم رآه الراكب قبل أن يضغط الزرّ. ومعامل الشاشة الأولى كتب مؤلّفه بجانبه
/// `// Arbitrary multiplier`، وهو أصدق تعليق في الملفّ.
///
/// وهذا الملفّ ليس توحيداً للحساب فحسب: هو المكان الذي تُغيَّر فيه الأسعار.
library;

/// فئة المركبة.
///
/// **المفتاح `id` لا الاسم المعروض.**
///
/// كانت الفئة تُمرَّر نصّاً مترجَماً: `Navigator.pop` يعيد
/// `AppLocalizations.of(context)!.oagoGo`، وتقارنه شاشة الطلب بالحرفيّة
/// `"Taibah Go"`. وهي تعمل اليوم بالصدفة وحدها — لأن النصوص العربيّة لم
/// تُترجَم بعد. فأوّل ترجمة عربيّة، أو أوّل إضافة للأردية أو البنغالية، تجعل
/// كلّ المقارنات تفشل وتسقط كلّ رحلة على الفرع الأخير: ×1.5 على كل راكب،
/// بلا رسالة خطأ وبلا سبب ظاهر.
///
/// المفتاح الآن ثابت لا يُترجَم، والاسم للعرض وحده.
enum VehicleTier {
  go('go', 0.8),
  executive('executive', 1.0),
  xl('xl', 1.5);

  const VehicleTier(this.id, this.multiplier);

  /// ما يُكتب في القاعدة ويُقارَن به — لا يُترجَم أبداً.
  final String id;

  /// معامل الفئة على مكوّنات الأجرة.
  ///
  /// **هذه الأرقام موروثة، وهي قرارك لا قراري.**
  ///
  /// أخذتُها كما هي من المسار الذي كان يُحصَّل فعلاً (`home_page`) كي لا
  /// يتغيّر سعرٌ بغير قصد أثناء إصلاح عطل. لاحظ أنّ `go` أقلّ من واحد، أي أنّ
  /// الفئة الأساسيّة تُباع بخصمٍ عن سعر الأساس — وهو ما ورثه القالب، لا ما
  /// اختاره أحد.
  final double multiplier;

  static VehicleTier fromId(String? id) => VehicleTier.values.firstWhere(
        (VehicleTier t) => t.id == id,
        orElse: () => VehicleTier.go,
      );
}

/// ثوابت الأجرة.
///
/// **أرقام القالب النيجيري، بالنايرا.**
///
/// `base 200` بعملةٍ يساوي فيها الدولار نحو ألف وحدة. وهي مكتوبة اليوم كأنّها
/// ريالات: مئتا ريال أساساً لأيّ رحلة داخل المدينة رقمٌ بلا معنى — أكثر من
/// أجرة رحلةٍ كاملة.
///
/// تُركت كما هي عمداً: تغييرها قرار عمل لا إصلاح عطل، ولا يُخمَّن. وجُمعت هنا
/// كي يكون تغييرها سطراً واحداً حين تقرّر.
class FareRates {
  const FareRates._();

  static const double base = 200;
  static const double perKm = 0.4;
  static const double perMinute = 0.3;

  /// أقلّ ما تُحصَّل به رحلة — يحمي من رحلةٍ قصيرة جداً تُحسب بأقلّ من كلفتها.
  static const double minimum = base;
}

/// التسعير — في مكان واحد.
///
/// كان في ثلاثة، وكان كلٌّ منها يعطي رقماً مختلفاً لنفس الرحلة:
///
///   شاشة اختيار الفئة   `200 + km × factor × 100`   ← ٦٠٠ لرحلة ١٠ كم
///   بطاقة التأكيد تحتها  `fareBreakdown × 0.8`      ← ١٦٨
///   ما يُحصَّل فعلاً      `fareBreakdown.total`       ← ٢١٠
///
/// ثلاثة أسعار لرحلة واحدة، والمدفوع لا يطابق أيّاً منها — وزيادةٌ ٢٥٪ فوق آخر
/// رقم رآه الراكب قبل أن يضغط الزرّ. ومعامل الشاشة الأولى كتب مؤلّفه بجانبه
/// `// Arbitrary multiplier`، وهو أصدق تعليق في الملفّ.
///
/// وهذا الملفّ ليس توحيداً للحساب فحسب: هو المكان الذي تُغيَّر فيه الأسعار.
library;

/// فئة المركبة.
///
/// **المفتاح `id` لا الاسم المعروض.**
///
/// كانت الفئة تُمرَّر نصّاً مترجَماً: `Navigator.pop` يعيد
/// `AppLocalizations.of(context)!.oagoGo`، وتقارنه شاشة الطلب بالحرفيّة
/// `"Taibah Go"`. وهي تعمل اليوم بالصدفة وحدها — لأن النصوص العربيّة لم
/// تُترجَم بعد. فأوّل ترجمة عربيّة، أو أوّل إضافة للأردية أو البنغالية، تجعل
/// كلّ المقارنات تفشل وتسقط كلّ رحلة على الفرع الأخير: ×1.5 على كل راكب،
/// بلا رسالة خطأ وبلا سبب ظاهر.
///
/// المفتاح الآن ثابت لا يُترجَم، والاسم للعرض وحده.
enum VehicleTier {
  go('go', 1.0),
  executive('executive', 1.0),
  xl('xl', 1.0);

  const VehicleTier(this.id, this.multiplier);

  /// ما يُكتب في القاعدة ويُقارَن به — لا يُترجَم أبداً.
  final String id;

  /// معامل الفئة على **أجرة الرحلة** — لا على عمولة المنصّة.
  ///
  /// **والثلاثة اليوم واحد، عن قصد.** التعرفة التي حدّدها صاحب المشروع تعرفةٌ
  /// واحدة: تسعة ريالات لأوّل خمسة كيلومترات، وريالٌ لكلّ كيلومتر بعدها،
  /// وخمسة ريالات عمولة. ولم تُحدَّد فروقٌ بين الفئات، فوضعُ معاملٍ مخترَع
  /// (٠٫٨ أو ١٫٥ كما ورثنا من القالب) يجعل السعر المعروض على الراكب مخالفاً
  /// للتعرفة المعلنة — والفئة الأولى تحديداً كانت ستُباع بأقلّ من التسعة.
  ///
  /// فالفئات الثلاث تُعرَض بسعرٍ واحد حتى تُحدَّد تعرفة كلٍّ منها. وحين
  /// تُحدَّد، يُغيَّر هذا السطر وحده.
  final double multiplier;

  static VehicleTier fromId(String? id) => VehicleTier.values.firstWhere(
        (VehicleTier t) => t.id == id,
        orElse: () => VehicleTier.go,
      );
}

/// تعرفة الأجرة — بالريال السعودي.
///
/// **أرقام صاحب المشروع، لا أرقام القالب.** كانت هنا تعرفة القالب النيجيري
/// بالنايرا (`base 200` و`0.4/km` و`0.3/min`) تُقرأ كأنّها ريالات: مئتا ريال
/// أساساً لأيّ رحلة داخل المدينة.
///
///   أوّل خمسة كيلومترات        ٩ ريالات
///   كلّ كيلومتر بعدها          ريال واحد
///   عمولة المنصّة              ٥ ريالات ثابتة
///
/// فرحلةُ ثلاثة كيلومترات ١٤ ريالاً، ورحلةُ عشرة ١٩ ريالاً.
///
/// **وثلاثة أشياء يُقالان صراحةً:**
///
/// **الزمن لا يُحسب.** لا شقّ زمنيّ في هذه التعرفة، فرحلةٌ زحفت في زحام
/// المسجد النبويّ ساعةً تُحصَّل كرحلةٍ قطعت المسافة نفسها في عشر دقائق. هذا
/// قرارُ صاحب التعرفة لا سهوٌ منه، ومكانه الملاحظات كي يُراجَع بعد أوّل شهر
/// تشغيل.
///
/// **والكيلومتر يُحسب بكسره.** ٧٫٣ كم = ٩ + ٢٫٣ = ١١٫٣ زائد العمولة. تقريبُه
/// لأعلى قرارُ تسعيرٍ آخر لم يُطلب، والتناسب أقرب إلى ما يتوقّعه الراكب حين
/// يرى المسافة أمامه.
///
/// **والعمولة يدفعها الراكب فوق الأجرة** — «زائد خمسة ريالات» — فهي تدخل في
/// ما يُحصَّل، وتُطرح من نصيب السائق في شاشة أرباحه.
class FareRates {
  const FareRates._();

  /// أوّل مسافة مشمولة في السعر الأساسي.
  static const double includedKm = 5;

  /// ثمن تلك المسافة، مهما قصرت الرحلة.
  static const double includedFare = 9;

  /// وما زاد على `includedKm`.
  static const double perExtraKm = 1;

  /// عمولة المنصّة — ثابتة لا تتبع مسافةً ولا فئة.
  static const double platformFee = 5;

  /// أقلّ ما تُحصَّل به رحلة: السعر الأساسي وعمولته، وهو ما تعطيه المعادلة
  /// نفسها لرحلةٍ صفريّة المسافة. مكتوبٌ صراحةً لأنّ الرحلات القديمة التي لا
  /// تحمل تفصيلاً تُسوّى به.
  static const double minimum = includedFare + platformFee;
}
